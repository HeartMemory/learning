public class Solution {
    // TODO: 返回那个出现次数【严格超过 n/2】的元素（题目保证它一定存在）。
    //
    //   ★ 先看清约束里的那把钥匙：「出现次数 > n/2」——不是"最多"，是"超过一半"。
    //     这一个字之差，决定了这道题有 O(1) 空间的解法（普通"求众数"是没有的）。
    //
    //   ── 路线 A：排序（一行，先拿个 AC 找感觉，但面试官会追问代价）
    //     排序后中间那个数（下标 n/2）一定是答案。自己推一遍为什么：
    //       一个出现超过一半的元素，无论怎么排，它占的位置都【跨过中点】。
    //     代价：O(n log n) 时间；而且改了原数组（除非先拷贝，那是 O(n) 空间）。
    //
    //   ── 路线 B：哈希计数（你 09-14~09-16 已经练熟的）
    //     Dictionary 数一遍，边数边判"有没有到 n/2 + 1"→ 命中即可提前返回。
    //     代价：O(n) 时间，但 O(n) 空间 —— 违背了题目暗示的"能不能更省"。
    //
    //   ── 路线 C：摩尔投票（Boyer–Moore Voting）⭐ 今天该写的
    //     生活模型先想这个：**两军对垒，不同阵营的人相遇就【同归于尽】**。
    //     规则只有三条：
    //       ① 擂台上站着一个【候选者】，手里记着"他还有多少张票"
    //       ② 遇到跟候选者【同阵营】的人 → 票 +1
    //       ③ 遇到【不同阵营】的人 → 票 -1（两人同归于尽）
    //     然后就是今天唯一需要你自己想通的那一步：
    //       **票减到 0 的时候该怎么办？**（提示：擂台空了 → 下一个人上位，票数重置为 1）
    //
    //     ★★ 为什么最后站在擂台上的那个一定是答案？（这才是本题的真正考点，别跳）
    //       用反证法想：设多数元素是 M，它出现 m 次，其余所有元素加起来是 (n - m) 次。
    //       "同归于尽"最多能消耗掉多少个 M？—— 每一次同归于尽，都要【拿一个非 M 去换】。
    //       所以 M 最多被抵消 (n - m) 次，而 m > n/2 → m > n - m → **换完之后 M 一定还有剩**。
    //       其余元素的票数上限就是它自己的出现次数，谁也活不过 M。
    //
    //   ★ 实现时的一个坑（先想清楚再写）：
    //       "票数为 0 → 换人"和"当前元素与候选者是否相同"这两步，谁先谁后？
    //       写成"先比后判"会出现什么？（拿 {2,3,4,5,5,5,5} 手推一遍，注意第 5 个数字那一刻）
    //
    //   复杂度目标：**O(n) 时间、O(1) 空间**（整个算法只要两个变量）。
    //
    //   ★ 写完的验收（照 0136 那次的老规矩）：10 组用例全绿之后，回头核对"形状"——
    //     答案在开头 / 末尾 / 中间 / 单元素 / 全同 / 负数 / 答案是 0 / 两阵营交替，
    //     这些形状每种都对应了投票法里一个不同的分支，缺哪种就等于漏测一条路径。
    //
    //   ★ 进阶（AC 之后想，面试高频追问）：
    //     ① 如果【不保证】多数元素存在，上面这个算法还能用吗？要怎么补救？
    //        （提示：投票只保证"候选人"是答案，不保证"真的有答案"——补一次复核要几趟？）
    //     ② 如果要求找"出现次数 > n/3"的所有元素呢？（提示：擂台不止一个）
    public int MajorityElement(int[] nums) {
        int times = 1;
        int result = nums[0];
        for(int i = 1;i < nums.Length; i++)
        {
            if(times == 0) result = nums[i];
            if(nums[i] == result) times++;
            else times--;
            if(times > (nums.Length / 2)) return result; 
        }
        return result;
    }
}
